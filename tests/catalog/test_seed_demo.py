"""``python -m rootcause.catalog.seed_demo --path <warehouse.duckdb>`` (RED).

``seed_demo(path, *, connections, catalog, settings)`` registers the demo warehouse
as a DuckDB connection named ``DEMO_CONNECTION_NAME``, imports its catalog, selects
every table and column, copies descriptions from
``rootcause.evals.manufacturing.table_docs.TABLE_DOCS`` and marks the connection
verified only after a read-only probe succeeded. It is idempotent: re-running it for
the same file reuses the connection (matched by its absolute path). ``main(argv)``
wires it to the application database (tested in ``tests/db/integration``).

The warehouse here is generated by the real generator (2 days), so the table names
match ``TABLE_DOCS``; a handmade file covers undocumented tables and columns.
"""

import asyncio
import uuid
from collections.abc import Coroutine
from pathlib import Path
from typing import Any

import duckdb
import pytest

pytestmark = pytest.mark.unit


def _run[T](coroutine: Coroutine[Any, Any, T]) -> T:
    return asyncio.run(coroutine)


@pytest.fixture(scope="module")
def generated_warehouse(tmp_path_factory: pytest.TempPathFactory) -> Path:
    from rootcause.evals.manufacturing import GeneratorConfig, generate
    from rootcause.evals.manufacturing.writers import write_duckdb

    path = tmp_path_factory.mktemp("demo") / "warehouse.duckdb"
    write_duckdb(generate(GeneratorConfig(seed=7, days=2)), path)
    return path


@pytest.fixture
def demo_warehouse(generated_warehouse: Path, tmp_path: Path) -> Path:
    """A private copy per test (the seed must never write to it; tests may compare bytes)."""
    copy = tmp_path / "warehouse.duckdb"
    copy.write_bytes(generated_warehouse.read_bytes())
    return copy


def _seed(path: Path, connections: Any, catalog: Any, settings: Any) -> Any:
    from rootcause.catalog.seed_demo import seed_demo

    return _run(seed_demo(path, connections=connections, catalog=catalog, settings=settings))


def test_seed_registers_a_verified_duckdb_connection(
    demo_warehouse: Path, connections: Any, catalog: Any, settings: Any
) -> None:
    from rootcause.catalog.seed_demo import DEMO_CONNECTION_NAME

    result = _seed(demo_warehouse, connections, catalog, settings)

    record = _run(connections.get(result.connection_id))
    assert record is not None
    assert record.kind == "duckdb"
    assert record.name == DEMO_CONNECTION_NAME
    assert record.path == str(demo_warehouse.resolve())
    assert record.encrypted_secret is None
    assert record.read_only_verified_at is not None


def test_seed_imports_and_selects_every_table_and_column(
    demo_warehouse: Path, connections: Any, catalog: Any, settings: Any
) -> None:
    from rootcause.evals.manufacturing.table_docs import TABLE_DOCS

    result = _seed(demo_warehouse, connections, catalog, settings)

    tables = _run(catalog.list_tables(result.connection_id))
    assert sorted(t.name for t in tables) == sorted(TABLE_DOCS)
    assert {t.schema for t in tables} == {"main"}
    assert all(t.selected for t in tables)
    assert all(c.selected for t in tables for c in t.columns)
    assert result.tables == len(tables)
    assert result.columns == sum(len(t.columns) for t in tables)


def test_seed_copies_table_and_column_descriptions_from_table_docs(
    demo_warehouse: Path, connections: Any, catalog: Any, settings: Any
) -> None:
    from rootcause.evals.manufacturing.table_docs import TABLE_DOCS

    result = _seed(demo_warehouse, connections, catalog, settings)

    for table in _run(catalog.list_tables(result.connection_id)):
        doc = TABLE_DOCS[table.name]
        assert table.description == doc.description
        for column in table.columns:
            assert column.description == doc.columns.get(column.name), (table.name, column.name)


def test_seed_never_writes_to_the_warehouse(
    demo_warehouse: Path, connections: Any, catalog: Any, settings: Any
) -> None:
    before = demo_warehouse.read_bytes()

    _seed(demo_warehouse, connections, catalog, settings)

    assert demo_warehouse.read_bytes() == before


def test_seed_is_idempotent_for_the_same_file(
    demo_warehouse: Path, connections: Any, catalog: Any, settings: Any
) -> None:
    first = _seed(demo_warehouse, connections, catalog, settings)
    tables_before = _run(catalog.list_tables(first.connection_id))

    second = _seed(demo_warehouse, connections, catalog, settings)

    assert second.connection_id == first.connection_id
    assert len(_run(connections.list())) == 1
    tables_after = _run(catalog.list_tables(second.connection_id))
    assert [t.id for t in tables_after] == [t.id for t in tables_before]
    assert (second.tables, second.columns) == (first.tables, first.columns)


def test_seed_resolves_a_relative_path(
    demo_warehouse: Path,
    connections: Any,
    catalog: Any,
    settings: Any,
    monkeypatch: pytest.MonkeyPatch,
) -> None:
    monkeypatch.chdir(demo_warehouse.parent)

    result = _seed(Path(demo_warehouse.name), connections, catalog, settings)

    record = _run(connections.get(result.connection_id))
    assert record.path == str(demo_warehouse.resolve())


def test_seed_leaves_undocumented_tables_and_columns_without_description(
    tmp_path: Path, connections: Any, catalog: Any, settings: Any
) -> None:
    path = tmp_path / "custom.duckdb"
    con = duckdb.connect(str(path))
    try:
        con.execute("CREATE TABLE plants (plant_id VARCHAR, extra_note VARCHAR)")
        con.execute("CREATE TABLE scratchpad (x INTEGER)")
    finally:
        con.close()

    result = _seed(path, connections, catalog, settings)

    tables = {t.name: t for t in _run(catalog.list_tables(result.connection_id))}
    assert tables["plants"].description == "Manufacturing sites."
    columns = {c.name: c for c in tables["plants"].columns}
    assert columns["plant_id"].description == "Plant identifier (P01, P02, ...)."
    assert columns["extra_note"].description is None
    assert tables["scratchpad"].description is None
    assert all(t.selected for t in tables.values())


@pytest.mark.parametrize("name", ["missing.duckdb", "not-a-database.duckdb"])
def test_seed_of_an_unusable_file_registers_nothing(
    tmp_path: Path, connections: Any, catalog: Any, settings: Any, name: str
) -> None:
    from rootcause.errors import RootCauseError

    path = tmp_path / name
    if name.startswith("not-a"):
        path.write_text("plain text, not DuckDB")

    with pytest.raises((RootCauseError, FileNotFoundError, ValueError)):
        _seed(path, connections, catalog, settings)

    assert _run(connections.list()) == ()


def test_main_requires_the_path_argument(capsys: pytest.CaptureFixture[str]) -> None:
    from rootcause.catalog.seed_demo import main

    with pytest.raises(SystemExit) as caught:
        main([])

    assert caught.value.code == 2
    assert "--path" in capsys.readouterr().err


def test_seed_result_is_immutable(
    demo_warehouse: Path, connections: Any, catalog: Any, settings: Any
) -> None:
    import dataclasses

    result = _seed(demo_warehouse, connections, catalog, settings)

    assert isinstance(result.connection_id, uuid.UUID)
    with pytest.raises(dataclasses.FrozenInstanceError):
        result.tables = 0
